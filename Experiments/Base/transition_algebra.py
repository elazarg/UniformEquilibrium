"""E18: exact transition-algebra and commutant calculations.

The algebra generated by supported transition, payoff, and observation
operators is available even without an external game symmetry.  This script
computes its dimension and the dimension of its commutant over Q by exact
Gaussian elimination.  Four archetypes distinguish hidden symmetry,
nilpotent/transient structure, and a generic full-matrix algebra.
"""

from __future__ import annotations

import json
from fractions import Fraction
from typing import Iterable

Matrix = tuple[tuple[Fraction, ...], ...]


def matrix(rows: Iterable[Iterable[int | Fraction]]) -> Matrix:
    return tuple(tuple(Fraction(value) for value in row) for row in rows)


def identity(n: int) -> Matrix:
    return matrix([[int(i == j) for j in range(n)] for i in range(n)])


def multiply(left: Matrix, right: Matrix) -> Matrix:
    n = len(left)
    return tuple(
        tuple(
            sum((left[i][k] * right[k][j] for k in range(n)), Fraction(0))
            for j in range(n)
        )
        for i in range(n)
    )


def flatten(value: Matrix) -> list[Fraction]:
    return [entry for row in value for entry in row]


def rank(rows: list[list[Fraction]]) -> int:
    if not rows:
        return 0
    work = [list(row) for row in rows]
    row_count = len(work)
    column_count = len(work[0])
    pivot_row = 0
    for column in range(column_count):
        pivot = next(
            (row for row in range(pivot_row, row_count) if work[row][column] != 0),
            None,
        )
        if pivot is None:
            continue
        work[pivot_row], work[pivot] = work[pivot], work[pivot_row]
        pivot_value = work[pivot_row][column]
        work[pivot_row] = [entry / pivot_value for entry in work[pivot_row]]
        for row in range(row_count):
            if row == pivot_row or work[row][column] == 0:
                continue
            coefficient = work[row][column]
            work[row] = [
                entry - coefficient * pivot_entry
                for entry, pivot_entry in zip(work[row], work[pivot_row])
            ]
        pivot_row += 1
        if pivot_row == row_count:
            break
    return pivot_row


def generated_algebra(generators: list[Matrix]) -> list[Matrix]:
    n = len(generators[0])
    basis: list[Matrix] = []

    def add_if_independent(value: Matrix) -> bool:
        old_rank = len(basis)
        if rank([flatten(item) for item in basis] + [flatten(value)]) > old_rank:
            basis.append(value)
            return True
        return False

    add_if_independent(identity(n))
    for generator in generators:
        add_if_independent(generator)

    changed = True
    while changed:
        changed = False
        for value in list(basis):
            for generator in generators:
                changed = add_if_independent(multiply(value, generator)) or changed
    return basis


def commutant_dimension(generators: list[Matrix]) -> int:
    n = len(generators[0])
    equations: list[list[Fraction]] = []
    for generator in generators:
        for i in range(n):
            for j in range(n):
                equation = [Fraction(0) for _ in range(n * n)]
                for k in range(n):
                    equation[i * n + k] += generator[k][j]
                    equation[k * n + j] -= generator[i][k]
                equations.append(equation)
    return n * n - rank(equations)


def cyclic_shift(n: int) -> Matrix:
    return matrix([[int(j == (i + 1) % n) for j in range(n)] for i in range(n)])


def nilpotent_shift(n: int) -> Matrix:
    return matrix([[int(j == i + 1) for j in range(n)] for i in range(n)])


def summarize(name: str, generators: list[Matrix]) -> dict:
    n = len(generators[0])
    algebra = generated_algebra(generators)
    return {
        "name": name,
        "state_dimension": n,
        "algebra_dimension": len(algebra),
        "full_matrix_dimension": n * n,
        "commutant_dimension": commutant_dimension(generators),
    }


def run() -> dict:
    identity_only = summarize("identity_only", [identity(3)])
    cyclic = summarize("cyclic_group_algebra", [cyclic_shift(4)])
    nilpotent = nilpotent_shift(4)
    transient = summarize("nilpotent_transient_algebra", [nilpotent])
    diagonal = matrix([[0, 0, 0], [0, 1, 0], [0, 0, 2]])
    full = summarize("cyclic_plus_distinguishing_payoff", [cyclic_shift(3), diagonal])

    assert identity_only["algebra_dimension"] == 1
    assert identity_only["commutant_dimension"] == 9
    assert cyclic["algebra_dimension"] == 4
    assert cyclic["commutant_dimension"] == 4
    assert transient["algebra_dimension"] == 4
    assert transient["commutant_dimension"] == 4
    assert multiply(multiply(multiply(nilpotent, nilpotent), nilpotent), nilpotent) == matrix(
        [[0, 0, 0, 0] for _ in range(4)]
    )
    assert full["algebra_dimension"] == 9
    assert full["commutant_dimension"] == 1

    return {
        "experiment": "E18",
        "status": "passed",
        "examples": [identity_only, cyclic, transient, full],
        "nilpotent_radical_candidate": {
            "generator_nilpotency_index": 4,
            "strict_power_span_dimension": 3,
            "semisimple_scalar_quotient_dimension": 1,
        },
        "conclusion": (
            "Endpoint operators can generate anything from a highly symmetric "
            "commutative algebra to the full matrix algebra.  Nilpotent transition "
            "modes naturally form a transient radical candidate."
        ),
        "limitation": (
            "The script computes algebra and commutant dimensions; it does not yet "
            "extract the actual endpoint operators from Lean or compute a general Jacobson radical."
        ),
    }


if __name__ == "__main__":
    print(json.dumps(run(), indent=2, sort_keys=True))
