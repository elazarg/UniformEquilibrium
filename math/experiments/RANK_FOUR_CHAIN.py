if __name__ == '__main__':
    donors = (3, 3, 1, 0)
    schedules = [tuple(tuple(map(int,r)) for r in s.split('.')) for s in SCHEDULES]
    tetrahedra = []
    for h, ids, _ in CELLS:
        cell = tuple(POINTS[i] for i in ids)
        assert h in (1, 2)
        for y in cell:
            assert min(y)>=0 and sum(y)>0
            assert y[1]<=3*y[0] and y[2]<=3*(y[0]+y[3])
            assert y[h]<=y[3-h]
        tetrahedra.append(cell)
    check_partition(tetrahedra, Fraction(81, 112))
    words = gains = 0
    for (h,ids,s),cell in zip(CELLS,tetrahedra):
        p = donors[h]
        perm = (h, *(i for i in PLAYERS if i not in (h,p)), p)
        faces = tuple((i,perm.index(donors[j]),k) for i,j in enumerate(perm)
                      for k in PLAYERS if perm[k] not in (j,donors[j]))
        schedule = tuple(tuple(perm.index(i) for i in owners) for owners in schedules[s])
        vertices = tuple(tuple(v[i] for i in perm) for v in cell)
        w,b = check_cell(schedule,vertices,faces)
        words += w
        gains += b
    print(len(CELLS), 'tetrahedra,', words, 'weighted words,', gains,
          'exact Bernstein inequalities')
